/**
 * Generates a clean, unique meeting room slug (e.g. twx-abc-def-ghi)
 * Requirement 1.3
 */
export const generateUniqueMeetingId = (): string => {
  const chars = 'abcdefghijklmnopqrstuvwxyz';
  const getRandomChunk = (len: number) => {
    let result = '';
    for (let i = 0; i < len; i++) {
      result += chars.charAt(Math.floor(Math.random() * chars.length));
    }
    return result;
  };

  return `twx-${getRandomChunk(3)}-${getRandomChunk(3)}-${getRandomChunk(3)}`;
};

/**
 * Sanitizes and formats custom meeting ID input
 * Requirement 1.4
 */
export const sanitizeCustomMeetingId = (input: string): string => {
  let code = input.trim();
  try {
    const url = new URL(code);
    code = url.pathname.split('/').filter(Boolean).pop() || '';
  } catch { code = code.split(/[?#]/)[0]; }
  return code
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
};

// Our own auto-generated slug shape (twx-xxx-xxx-xxx) -- used to tell a legit, app-issued room
// id apart from an arbitrary path. nginx mirrors this same pattern for its bare-root route (see
// talk-proxy.conf.local); keep the two in sync if this ever changes. Anchored to the exact
// 3-letter-group shape generateUniqueMeetingId() produces, not just the twx- prefix -- a custom
// slug a user typed that happens to start with "twx-" but isn't this exact shape must still fall
// through to the /meet/ path, since nginx's own route won't match it either.
const AUTO_GENERATED_ROOM_PATTERN = /^twx-[a-z]{3}-[a-z]{3}-[a-z]{3}$/;
// Free/instant meetings from the homepage reuse the same twx- shape with this prefix, so they're
// also covered by AUTO_GENERATED_ROOM_PATTERN once sanitized -- see buildMeetingPath below.
const INSTANT_ROOM_PREFIX = 'instant-';

/**
 * True for our own auto-generated twx-xxx-xxx-xxx slug shape -- used client-side to decide
 * whether a bare top-level path (e.g. /twx-abc-def-ghi) is actually a room id before rendering
 * the meeting page there, as a defense-in-depth check behind nginx's own matching route.
 */
export const isAutoGeneratedRoomId = (roomId: string): boolean => AUTO_GENERATED_ROOM_PATTERN.test(sanitizeCustomMeetingId(roomId));

/**
 * Builds the room path for a meeting id: bare "/<id>" for our own auto-generated twx-xxx-xxx-xxx
 * slugs (nginx recognizes that exact shape at the root and proxies it straight to the app),
 * "/instant/<id>" for the homepage's free instant meetings, and "/meet/<id>" as the fallback for
 * a user-typed custom slug, which doesn't necessarily match either pattern.
 */
export const buildMeetingPath = (roomId: string): string => {
  const cleanId = sanitizeCustomMeetingId(roomId);

  if (cleanId.startsWith(INSTANT_ROOM_PREFIX)) {
    return `/instant/${cleanId}`;
  }
  if (AUTO_GENERATED_ROOM_PATTERN.test(cleanId)) {
    return `/${cleanId}`;
  }
  return `/meet/${cleanId}`;
};

/**
 * Builds the full meeting room URL for Toowix Meet web app
 */
export const getMeetingUrl = (roomId: string): string => {
  const base = typeof window !== 'undefined' && window.location.origin
    ? window.location.origin
    : (import.meta.env.VITE_APP_URL || 'http://localhost:3000');
  return `${base}${buildMeetingPath(roomId)}`;
};
